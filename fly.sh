#!/usr/bin/env bash
# Fly build script - builds and auto-updates compile_commands.json for clangd.
# Run this instead of raw `bazel build` to keep clangd working after adding new files.
#
# Usage:
#   ./fly.sh build [target...]      - Build + refresh clangd (default)
#   ./fly.sh test [target...]      - Test + refresh clangd
#   ./fly.sh buildonly [target...] - Build only, no clangd refresh
#   ./fly.sh refresh               - Refresh compile_commands.json only
#   ./fly.sh check                 - Build, test, and refresh clangd
#   ./fly.sh install               - Create build/ with symlinks
set -euo pipefail

FLY_ROOT="$(cd "$(dirname "$0")" && pwd)"
DEFAULT_BUILD_TARGETS="//src/..."
DEFAULT_TEST_TARGETS="//src/..."

# Respect .bazelversion if present
if [ -f "$FLY_ROOT/.bazelversion" ]; then
    export USE_BAZEL_VERSION="$(cat "$FLY_ROOT/.bazelversion")"
fi

# Python path auto-detection
# Generates .bazelrc.user with machine-specific Python 3.12 include/link paths.
# Different machines may have Python 3.12 headers at /usr/include or /usr/local/include.
detect_python_paths() {
    local python_exe="python3.12"
    if ! command -v "$python_exe" &>/dev/null; then
        echo "ERROR: $python_exe not found. Please install Python 3.12." >&2
        exit 1
    fi

    local user_rc="$FLY_ROOT/.bazelrc.user"
    local include_path lib_dir

    include_path=$($python_exe -c "import sysconfig; print(sysconfig.get_path('include'))")
    lib_dir=$($python_exe -c "import sysconfig; print(sysconfig.get_config_var('LIBDIR'))")

    # Validate paths exist
    if [ ! -f "$include_path/Python.h" ]; then
        echo "ERROR: Python.h not found at $include_path" >&2
        echo "Install python3.12-dev or equivalent for your system." >&2
        exit 1
    fi

    cat > "$user_rc" <<EOF
# AUTO-GENERATED by fly.sh - do not edit manually
# Python 3.12 paths detected on $(hostname) at $(date -Iseconds)
build --copt=-I${include_path}
build --host_cxxopt=-I${include_path}
build --linkopt=-L${lib_dir}
build --linkopt=-lpython3.12
EOF
    echo ">>> Python 3.12: include=${include_path}, lib=${lib_dir}"
}

refresh_clangd() {
    echo ">>> Refreshing compile_commands.json for clangd..."
    cd "$FLY_ROOT"

    local all_targets
    all_targets=$(bazel query "kind('cc_library|cc_binary|cc_test', //src/...)" 2>/dev/null | sort -u)

    if [ -z "$all_targets" ]; then
        echo "WARNING: No targets discovered. Building first..."
        bazel build $DEFAULT_BUILD_TARGETS 2>/dev/null || true
        all_targets=$(bazel query "kind('cc_library|cc_binary|cc_test', //src/...)" 2>/dev/null | sort -u)
    fi

    local count
    count=$(echo "$all_targets" | wc -w)
    echo ">>> Found $count targets for clangd"

    # Use local refresh tool (no Bazel target needed - avoids native.py_binary issue with Bazel 9)
    python3 "$FLY_ROOT/tools/refresh_compile_commands/refresh.py" \
        --targets $all_targets \
        --output "$FLY_ROOT/compile_commands.json" 2>&1 || {
        echo "WARNING: clangd refresh failed (non-fatal)" >&2
    }

    echo ">>> compile_commands.json updated ($count targets)"
}

# Install the pre-push git hook (幂等软链).
#
# git 不会随 clone 自动安装 hooks（安全设计），所以 scripts/pre-push 虽然纳入
# 版本控制，仍需手动激活。这里在 do_install 时幂等地把它软链到
# .git/hooks/pre-push，让门禁对当前环境生效。软链（而非复制）使得后续对
# scripts/pre-push 的修改无需重新安装即对所有环境生效。
#
# 幂等策略：
#   - 链接已存在且 target 正确 → 静默跳过
#   - 链接断开 / 指向他处 → 重建
#   - .git/hooks/pre-push 是普通文件（非我们建的软链）→ 警告但不覆盖
#   - scripts/pre-push 缺失 → 警告，不阻断 install
install_hooks() {
    local hook_src="$FLY_ROOT/scripts/pre-push"
    local hook_dst
    hook_dst="$(git rev-parse --git-dir 2>/dev/null)/hooks/pre-push"
    if [ -z "$hook_dst" ]; then
        echo "WARNING: not in a git repo, skipping pre-push hook install" >&2
        return 0
    fi

    if [ ! -f "$hook_src" ]; then
        echo "WARNING: scripts/pre-push not found, skipping pre-push hook install" >&2
        return 0
    fi

    # 确保源脚本可执行（软链不携带权限位，git 跟踪的 100755 在某些 checkout 下可能丢失）
    chmod +x "$hook_src" 2>/dev/null || true

    # 已正确软链 → 幂等跳过
    if [ -L "$hook_dst" ] && [ "$(readlink -f "$hook_dst")" = "$(readlink -f "$hook_src")" ]; then
        return 0
    fi

    # 已存在但不是我们的软链（普通文件/他人软链）→ 警告不覆盖，避免破坏用户自定义
    if [ -e "$hook_dst" ] && [ ! -L "$hook_dst" ]; then
        echo "WARNING: $hook_dst exists and is not a symlink; not overwriting." >&2
        echo "         To activate the project pre-push hook, remove it and rerun ./fly.sh install." >&2
        return 0
    fi

    mkdir -p "$(dirname "$hook_dst")"
    ln -sf "$hook_src" "$hook_dst"
    echo ">>> Installed pre-push hook: $hook_dst -> $hook_src"
}

do_install() {
    cd "$FLY_ROOT"
    local build_dir="$FLY_ROOT/build"
    local bazel_bin="$FLY_ROOT/bazel-bin"

    if [ ! -d "$bazel_bin/src" ]; then
        echo "ERROR: bazel-bin not found. Run './fly.sh build' first." >&2
        exit 1
    fi

    echo ">>> Installing to $build_dir/"
    rm -rf "$build_dir"
    mkdir -p "$build_dir/bin" "$build_dir/lib"
    mkdir -p "$build_dir/python/fly"
    mkdir -p "$build_dir/python/core"
    mkdir -p "$build_dir/python/storage"
    mkdir -p "$build_dir/python/agent"
    mkdir -p "$build_dir/python/log"
    mkdir -p "$build_dir/python/network"
    mkdir -p "$build_dir/python/task"
    mkdir -p "$build_dir/python/test"
    mkdir -p "$build_dir/python/solver"
    mkdir -p "$build_dir/python/message"

    # Binary + wrapper script
    ln -sf "$bazel_bin/src/main/cpp/fly" "$build_dir/bin/fly.bin"
    cat > "$build_dir/bin/fly" <<'WRAPPER'
#!/usr/bin/env bash
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BUILD_DIR="$(dirname "$SCRIPT_DIR")"
export FLY_BUILD="$BUILD_DIR"
export LD_LIBRARY_PATH="$BUILD_DIR/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
export PYTHONPATH="$BUILD_DIR/lib:$BUILD_DIR/python${PYTHONPATH:+:$PYTHONPATH}"
exec "$SCRIPT_DIR/fly.bin" "$@"
WRAPPER
    chmod +x "$build_dir/bin/fly"

    # C++ shared libs (export .so + lib*_so.so dependencies)
    for so in "$bazel_bin"/src/*/export/_fly_*.so; do
        [ -f "$so" ] && ln -sf "$so" "$build_dir/lib/"
    done
    for so in "$bazel_bin"/src/*/cpp/libfly_*_so.so; do
        [ -f "$so" ] && ln -sf "$so" "$build_dir/lib/"
    done

    # Python modules: .so 到模块根（sys.path 包含模块目录让 import _fly_X 可用），
    # .py 到 py/ 子目录（与源码树 src/X/py/ 结构一致，让两种布局的 import 路径统一）。
    # 模块根 __init__.py 从 src/X/__init__.py 软链（让模块成为合法 Python 包）。
    for mod in core log network task test storage agent solver message; do
        local so="$bazel_bin/src/$mod/export/_fly_${mod}.so"
        [ -f "$so" ] && ln -sf "$so" "$build_dir/python/$mod/"
        # 模块根 __init__.py（message 无 Python 源码，跳过）
        if [ -f "$FLY_ROOT/src/$mod/__init__.py" ]; then
            ln -sf "$FLY_ROOT/src/$mod/__init__.py" "$build_dir/python/$mod/__init__.py"
        fi
        # py/ 子包（log/message 无 Python 源码，跳过）
        if [ -d "$FLY_ROOT/src/$mod/py" ]; then
            mkdir -p "$build_dir/python/$mod/py"
            for py in "$FLY_ROOT/src/$mod/py/"*.py; do
                [ -f "$py" ] && ln -sf "$py" "$build_dir/python/$mod/py/"
            done
        fi
    done

    # fly package
    for py in "$FLY_ROOT/src/fly/"*.py; do
        [ -f "$py" ] && ln -sf "$py" "$build_dir/python/fly/"
    done

    # sitecustomize.py + .coveragerc MUST live at the top of build/python/
    # (which PYTHONPATH puts on sys.path before `site` runs) so CPython's
    # auto-import of sitecustomize fires before any `import fly`. This is what
    # makes early coverage instrumentation work — see sitecustomize.py docstring
    # and docs/coverage-testing.md §12.1. Symlink (not copy) keeps them in sync
    # with src/fly/ on edits.
    ln -sf "$FLY_ROOT/src/fly/sitecustomize.py" "$build_dir/python/sitecustomize.py"
    ln -sf "$FLY_ROOT/src/fly/.coveragerc" "$build_dir/python/.coveragerc"

    # Third-party Python packages (cloudpickle/numpy/scipy) from bazel @pip hub.
    #
    # Production `fly` embeds libpython and imports these packages at runtime.
    # Unlike the .so bindings above, the @pip wheels are NOT bazel runfiles for
    # the cc_binary, so we copy them into a standard site-packages layout that
    # setup_sys_path() in main.cpp adds to sys.path. This makes the installed
    # binary hermetic — it no longer reads cloudpickle/numpy/scipy from the
    # system site-packages.
    #
    # pytest is intentionally NOT copied: it is a test-only dep consumed by
    # py_test targets in the bazel sandbox, never imported by production fly.
    #
    # We copy (not symlink) the unpacked wheel tree because (1) wheels unpack
    # to multi-file directory trees, (2) bazel's external repos may be evicted
    # by `bazel clean`/disk pressure, breaking symlinks, and (3) scipy bundles
    # native .so libraries in scipy.libs/ whose permissions must be preserved.
    local pip_site="$build_dir/python/lib/python3.12/site-packages"
    mkdir -p "$pip_site"
    local output_base
    output_base="$(bazel --nohome_rc info output_base 2>/dev/null)"
    local pkg repo_root build_file_path
    for pkg in cloudpickle numpy scipy; do
        # Resolve the wheel's extracted repo root via cquery. The
        # :extracted_whl_files target emits a BUILD.bazel at the repo root;
        # we parse its path to locate site-packages/ without hardcoding the
        # internal "rules_python++pip+pip_312_<pkg>" repo-name string.
        build_file_path="$(bazel --nohome_rc cquery "@pip//$pkg:extracted_whl_files" \
            --output=starlark \
            --starlark:expr='str([f.path for f in target.files.to_list() if f.basename == "BUILD.bazel"][0])' \
            2>/dev/null)"
        if [ -z "$build_file_path" ]; then
            echo "ERROR: failed to resolve @pip//$pkg wheel layout" >&2
            exit 1
        fi
        repo_root="$(dirname "$output_base/$build_file_path")"
        if [ ! -d "$repo_root/site-packages" ]; then
            echo "ERROR: $pkg site-packages not found at $repo_root/site-packages" >&2
            exit 1
        fi
        # "site-packages/." merges the unpacked wheel contents (package dir +
        # .dist-info) into our combined site-packages root.
        cp -r "$repo_root/site-packages/." "$pip_site/"
    done

    echo ">>> Install complete: $build_dir/bin/fly"

    # 顺带激活 pre-push 门禁 hook（幂等，见 install_hooks 注释）。
    install_hooks
}

case "${1:-build}" in
    build)
        shift || true
        targets="${@:-$DEFAULT_BUILD_TARGETS}"
        detect_python_paths
        echo ">>> Building: $targets"
        bazel build $targets
        refresh_clangd
        echo ">>> Build complete. clangd index updated."
        ;;
    test)
        shift || true
        targets="${@:-$DEFAULT_TEST_TARGETS}"
        detect_python_paths
        echo ">>> Testing: $targets"
        bazel test $targets --test_output=errors
        echo ">>> Tests complete."
        ;;
    buildonly)
        shift || true
        targets="${@:-$DEFAULT_BUILD_TARGETS}"
        detect_python_paths
        echo ">>> Building (no clangd refresh): $targets"
        bazel build $targets
        ;;
    refresh)
        refresh_clangd
        echo ">>> clangd index refreshed."
        ;;
    check)
        shift || true
        targets="${@:-$DEFAULT_BUILD_TARGETS}"
        detect_python_paths
        echo ">>> Quick check: $targets"
        bazel build $targets
        test_output=$(bazel test //src/... --test_output=errors 2>&1)
        test_exit=$?
        echo "$test_output" | tail -20
        if [ $test_exit -ne 0 ]; then
            echo ">>> TESTS FAILED (exit code: $test_exit)"
            exit $test_exit
        fi
        refresh_clangd
        echo ">>> Check complete."
        ;;
    install)
        do_install
        ;;
    *)
        echo "Usage: $0 {build|test|buildonly|refresh|check|install} [target...]"
        echo ""
        echo "  build      Build + refresh clangd (default)"
        echo "  test       Run tests (no clangd refresh)"
        echo "  buildonly  Build without refreshing clangd"
        echo "  refresh    Only refresh compile_commands.json"
        echo "  check      Build, test, and refresh clangd"
        echo "  install    Create build/ with symlinks to bazel-bin artifacts"
        exit 1
        ;;
esac
